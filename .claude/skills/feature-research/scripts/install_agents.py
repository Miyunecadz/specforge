#!/usr/bin/env python3
"""install_agents.py: generate .claude/agents/ from agents-src/ (BUILD_SPEC §9, §10).

Run during setup, never during a run (it refuses while any run is active, and H1 blocks it).
- Installs exactly one researcher variant for the hook mode: web-researcher (identified)
  or web-researcher-fallback (fallback). The other variant's generated file is removed.
- Embeds the shared subagent rules verbatim (preloading does not work for a skill marked
  disable-model-invocation: true on this Claude Code version; plan decision b).
- Resolves the interpreter to an absolute path (project .venv if present, else python3 or
  python from PATH) and records it, with the hook mode, in .claude/feature-research.local.json.
- Checks every agent's tool list against its allowance; no workflow agent may have Skill,
  WebFetch, Agent/Task, a browser or MCP tool.

Never hand-edit .claude/agents/: edit agents-src/ and re-run this script.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path
from typing import Sequence

sys.path.insert(0, str(Path(__file__).resolve().parent))

from _lib import fsutil, hashing, modes, paths, runctx, schema  # noqa: E402

GENERATED_MARKER = "<!-- GENERATED by install_agents.py from agents-src/{src}. Do not edit; edit the source and re-run. -->"
RULES_BEGIN = "<!-- BEGIN SHARED RULES: .claude/skills/feature-research-subagent-rules/SKILL.md (verbatim) -->"
RULES_END = "<!-- END SHARED RULES -->"

# Complete tool allowance per agent (BUILD_SPEC §9). Bash for web-researcher is further
# restricted by H1 to the exact fetch_source.py form.
TOOL_ALLOWANCE = {
    "mockup-extractor": {"Read", "Write"},
    "requirements-parser": {"Read", "Write"},
    "gap-analyst": {"Read", "Write"},
    "web-researcher": {"WebSearch", "Read", "Write", "Bash"},
    "web-researcher-fallback": {"WebSearch", "Read", "Write"},
    "source-verifier": {"Read", "Write"},
    "feasibility-analyst": {"Read", "Write"},
    "question-generator": {"Read", "Write"},
    "doc-writer": {"Read", "Write"},
    "doc-reviewer": {"Read", "Write"},
    "eval-citation-grader": {"Read", "Write"},
}
FORBIDDEN_TOOLS = re.compile(r"^(Skill|WebFetch|Agent|Task|mcp__.*|.*[Bb]rowser.*|Monitor|Workflow)$")
RESEARCHERS = {"identified": "web-researcher", "fallback": "web-researcher-fallback"}
EVAL_ONLY = {"eval-citation-grader"}
BASE_WORKFLOW = ["mockup-extractor", "requirements-parser", "gap-analyst", "source-verifier",
                 "feasibility-analyst", "question-generator", "doc-writer", "doc-reviewer"]


class InstallError(RuntimeError):
    pass


def split_frontmatter(text: str) -> tuple[str, str]:
    if not text.startswith("---\n"):
        raise InstallError("missing YAML frontmatter")
    end = text.index("\n---\n", 4)
    return text[4:end], text[end + 5:]


def rules_body(repo: Path) -> str:
    src = repo / ".claude/skills/feature-research-subagent-rules/SKILL.md"
    _, body = split_frontmatter(src.read_text(encoding="utf-8"))
    return body.strip("\n")


def resolve_python(repo: Path) -> str:
    venv = repo / ".venv" / "bin" / "python"
    if venv.exists():
        return os.path.abspath(venv)
    for name in ("python3", "python"):
        found = shutil.which(name)
        if found:
            return os.path.abspath(found)
    raise InstallError("no Python interpreter found (.venv/bin/python, python3, python)")


def claude_version() -> str | None:
    try:
        out = subprocess.run(["claude", "--version"], capture_output=True, text=True, timeout=20)
    except (OSError, subprocess.TimeoutExpired):
        return None
    m = re.search(r"\d+\.\d+\.\d+", out.stdout)
    return m.group(0) if m else None


def parse_tools(front: str) -> list[str]:
    m = re.search(r"^tools:\s*(.+)$", front, re.M)
    if not m:
        raise InstallError("frontmatter has no tools: line (an explicit tool list is required)")
    return [t.strip() for t in m.group(1).split(",") if t.strip()]


def render(src: Path, rules: str, python: str, skill_dir: Path, preload: bool) -> str:
    front, body = split_frontmatter(src.read_text(encoding="utf-8"))
    name_m = re.search(r"^name:\s*(\S+)\s*$", front, re.M)
    if not name_m or name_m.group(1) != src.stem:
        raise InstallError(f"{src.name}: frontmatter name must equal the file stem {src.stem!r}")
    name = src.stem
    tools = parse_tools(front)
    bad = [t for t in tools if FORBIDDEN_TOOLS.match(t)]
    if bad:
        raise InstallError(f"{name}: forbidden tools {bad}")
    extra = set(tools) - TOOL_ALLOWANCE.get(name, set())
    if name not in TOOL_ALLOWANCE or extra:
        raise InstallError(f"{name}: tools {sorted(extra) or tools} exceed its allowance")
    if "{{SHARED_RULES}}" not in body:
        raise InstallError(f"{name}: body must contain the {{{{SHARED_RULES}}}} placeholder")
    if preload:
        front = front.rstrip("\n") + "\nskills:\n  - feature-research-subagent-rules\n"
        rules_block = "Your shared rules are preloaded from the feature-research-subagent-rules skill."
    else:
        rules_block = f"{RULES_BEGIN}\n{rules}\n{RULES_END}"
    body = (body.replace("{{SHARED_RULES}}", rules_block)
                .replace("{{PYTHON}}", python)
                .replace("{{SKILL_DIR}}", str(skill_dir)))
    leftover = re.findall(r"\{\{[A-Z_]+\}\}", body)
    if leftover:
        raise InstallError(f"{name}: unknown placeholders {leftover}")
    return f"---\n{front.rstrip(chr(10))}\n---\n\n{GENERATED_MARKER.format(src=src.name)}\n\n{body.lstrip(chr(10))}"


def install(repo: Path, hook_mode: str, session_ids: bool, preload: bool, include_eval: bool,
            version: str | None) -> dict:
    for m in (modes.NORMAL, modes.FIXTURE):
        if (paths.runs_root(repo, m) / ".active_run").exists():
            raise InstallError("a run is active; install_agents.py runs only during setup")
    skill_dir = paths.skill_dir(repo).resolve()
    src_dir = skill_dir / "agents-src"
    out_dir = repo / paths.AGENTS_REL
    python = resolve_python(repo)
    rules = rules_body(repo)
    researcher = RESEARCHERS[hook_mode]
    sources = sorted(src_dir.glob("*.md"))
    selected = []
    for src in sources:
        name = src.stem
        if name in RESEARCHERS.values() and name != researcher:
            continue
        if name in EVAL_ONLY and not include_eval:
            continue
        selected.append(src)
    out_dir.mkdir(parents=True, exist_ok=True)
    installed = []
    for src in selected:
        text = render(src, rules, python, skill_dir, preload)
        fsutil.atomic_write_bytes(out_dir / f"{src.stem}.md", text.encode("utf-8"))
        installed.append(src.stem)
    # Remove generated files that are no longer selected (e.g. the other researcher variant).
    for existing in out_dir.glob("*.md"):
        if existing.stem not in installed and "GENERATED by install_agents.py" in existing.read_text(encoding="utf-8"):
            existing.unlink()
    setup = {
        "schema_version": 1,
        "python": python,
        "repo_root": str(repo.resolve()),
        "skill_dir": str(skill_dir),
        "hook_mode": hook_mode,
        "session_ids": session_ids,
        "preload_rules": preload,
        "researcher_variant": researcher,
        "workflow_agents": BASE_WORKFLOW[:3] + [researcher] + BASE_WORKFLOW[3:],
        "installed_agents": installed,
        "rules_sha256": hashing.sha256_text(rules),
        "agents_src_sha256": hashing.sha256_text(
            "\n".join(f"{s.name}:{hashing.sha256_file(s)}" for s in sources)),
        "claude_version": version,
        "installed_at": runctx.now_iso(),
    }
    schema.check("setup", setup, what=str(paths.SETUP_REL))
    fsutil.atomic_write_json(repo / paths.SETUP_REL, setup)
    return setup


def main(argv: Sequence[str] | None = None, repo: Path | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--hook-mode", choices=sorted(RESEARCHERS), default="identified",
                    help="identified: hooks see agent_type (confirmed on Claude Code 2.1.296)")
    ap.add_argument("--no-session-ids", action="store_true",
                    help="use heartbeat expiry instead of session binding (only if the payload lacks session_id)")
    ap.add_argument("--preload", action="store_true",
                    help="use skills: preloading instead of embedding (does not work while the rules skill "
                         "has disable-model-invocation: true)")
    ap.add_argument("--include-eval-agents", action="store_true")
    args = ap.parse_args(None if argv is None else list(argv)[1:])
    repo = repo or paths.REPO_ROOT
    try:
        setup = install(repo, args.hook_mode, not args.no_session_ids, args.preload,
                        args.include_eval_agents, claude_version())
    except (InstallError, schema.SchemaError, OSError, ValueError) as exc:
        print(json.dumps({"ok": False, "error": str(exc)}))
        return 1
    print(json.dumps({"ok": True, **{k: setup[k] for k in (
        "python", "hook_mode", "researcher_variant", "installed_agents", "preload_rules", "claude_version")}},
        indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main())
