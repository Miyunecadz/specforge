AGENT_TMPL = """---
name: {name}
description: test agent {name}.
tools: {tools}
model: sonnet
---

# {name}

{{{{SHARED_RULES}}}}

Run {{{{PYTHON}}}} {{{{SKILL_DIR}}}}/scripts/fetch_source.py when told.
"""


def add_src(repo, name, tools="Read, Write"):
    p = repo / ".claude/skills/feature-research/agents-src" / f"{name}.md"
    p.write_text(AGENT_TMPL.format(name=name, tools=tools))
    return p


def install(repo, mode="identified", **kw):
    return ia.install(repo, mode, True, kw.get("preload", False), kw.get("include_eval", False), "2.1.296")


def test_exactly_one_researcher_variant_matches_hook_mode(repo):
    add_src(repo, "web-researcher", "WebSearch, Read, Write, Bash")
    add_src(repo, "web-researcher-fallback", "WebSearch, Read, Write")
    agents = repo / ".claude/agents"
    setup = install(repo, "identified")
    names = sorted(p.stem for p in agents.glob("*.md"))
    assert "web-researcher" in names and "web-researcher-fallback" not in names
    assert setup["researcher_variant"] == "web-researcher" and "web-researcher" in setup["workflow_agents"]
    setup = install(repo, "fallback")
    names = sorted(p.stem for p in agents.glob("*.md"))
    assert "web-researcher-fallback" in names and "web-researcher" not in names
    assert setup["hook_mode"] == "fallback"


def test_embedded_rules_match_source_exactly(repo):
    install(repo)
    rules = ia.rules_body(repo)
    for agent in (repo / ".claude/agents").glob("*.md"):
        text = agent.read_text()
        m = re.search(re.escape(ia.RULES_BEGIN) + r"\n(.*)\n" + re.escape(ia.RULES_END), text, re.S)
        assert m and m.group(1) == rules, agent.name
        assert "{{" not in text


def test_installed_agents_in_this_repo_have_no_drift():
    """The real .claude/agents/ must match the current shared rules and agents-src."""
    agents = sorted((REPO / ".claude/agents").glob("*.md"))
    if not agents:
        pytest.skip("NOT RUN: install_agents.py has not been run in this checkout")
    rules = ia.rules_body(REPO)
    setup = json.loads((REPO / ".claude/feature-research.local.json").read_text())
    for agent in agents:
        text = agent.read_text()
        m = re.search(re.escape(ia.RULES_BEGIN) + r"\n(.*)\n" + re.escape(ia.RULES_END), text, re.S)
        assert m and m.group(1) == rules, f"{agent.name}: embedded rules differ from the source; re-run install_agents.py"
        src = REPO / ".claude/skills/feature-research/agents-src" / agent.name
        expected = ia.render(src, rules, setup["python"], REPO / ".claude/skills/feature-research", False)
        assert text == expected, f"{agent.name}: differs from agents-src; never hand-edit .claude/agents/"


